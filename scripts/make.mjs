#!/usr/bin/env node
// Make any Agency 2026 artefact from a content file.
//   node scripts/make.mjs samples/print/handout.json            -> out/print/handout.{html,pdf,png}
//   node scripts/make.mjs my-content.json --out build/          # any folder
//   node scripts/make.mjs --all [--check]                       # every samples/**/*.json that names a "template"
//   node scripts/make.mjs --list                                # every template with its size and purpose
// A content file is JSON with "template": "<family>/<name>" (a module in templates/) and the fields that template documents.
// --check exits 1 if a page overflows, text does not fit its box, a bundled font failed to load, an image has no alt text, or the
// page has no lang or title. Text contrast below WCAG AA (4.5:1, 3:1 for large text) is a warning; --strict makes it a fault too.
// Content files may waive a checked false positive: "a11y": {"ignore": ["start of the element's text"]}.
import fs from 'node:fs';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { htmlToPdf, htmlToPng, close, ROOT } from './lib/browser.mjs';

const a = process.argv.slice(2);
const flag = (k) => a.includes('--' + k);
const val = (k, d) => { const i = a.indexOf('--' + k); return i >= 0 ? a[i + 1] : d; };
const OUT = path.resolve(val('out', path.join(ROOT, 'out')));

const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => e.isDirectory() ? walk(path.join(d, e.name)) : [path.join(d, e.name)]);

export async function loadTemplate(name) {
  const f = path.join(ROOT, 'templates', name + '.mjs');
  if (!fs.existsSync(f)) throw new Error(`no template ${name} (expected ${path.relative(ROOT, f)}); run --list`);
  return import(pathToFileURL(f).href);
}

export async function make(file, o = {}) {
  const data = JSON.parse(fs.readFileSync(file, 'utf8'));
  if (!data.template) throw new Error(`${file}: no "template" field`);
  const tpl = await loadTemplate(data.template);
  const meta = typeof tpl.meta === 'function' ? tpl.meta(data) : tpl.meta;
  const family = data.template.split('/')[0];
  const name = data.name ?? path.basename(file, '.json');
  const dir = path.join(o.out ?? OUT, family);
  fs.mkdirSync(dir, { recursive: true });
  const base = path.relative(dir, ROOT).split(path.sep).join('/') || '.';
  const ctx = { base, file, data, meta, T: null };
  const body = await tpl.render(data, ctx);
  const html = `<!doctype html>\n<html lang="${data.lang ?? 'en'}"><head><meta charset="utf-8"><title>${(data.title ?? name).replace(/</g, '')}</title>\n` +
    `<!-- GENERATED by scripts/make.mjs from ${path.relative(ROOT, path.resolve(file))} with templates/${data.template}.mjs. Edit the content file, not this. -->\n` +
    `<link rel="stylesheet" href="${base}/styles/agency.css">${meta.css ? `<style>${meta.css}</style>` : ''}</head>\n<body>${body}</body></html>\n`;
  const htmlFile = path.join(dir, name + '.html');
  fs.writeFileSync(htmlFile, html);
  const rep = meta.kind === 'pdf'
    ? await htmlToPdf(htmlFile, path.join(dir, name + '.pdf'), { vw: meta.vw, vh: meta.vh, scale: meta.scale ?? 2, a11y: data.a11y, strict: flag('strict') })
    : await htmlToPng(htmlFile, path.join(dir, name + '.png'), { width: meta.width, height: meta.height, scale: meta.scale ?? 1, pdf: meta.pdf, transparent: meta.transparent, a11y: data.a11y, strict: flag('strict') });
  const outs = [rep.pdf, ...rep.pngs].filter(Boolean).map((f) => path.relative(process.cwd(), f));
  console.log(`${rep.faults.length ? 'FAULT' : 'ok   '} ${path.relative(ROOT, path.resolve(file))} -> ${outs.join(', ')}`);
  for (const f of rep.faults) console.log('      - ' + f);
  for (const w of rep.warnings ?? []) console.log('      warn ' + w);
  return rep;
}

async function list() {
  for (const f of walk(path.join(ROOT, 'templates')).filter((f) => f.endsWith('.mjs') && !f.includes('/lib/')).sort()) {
    const name = path.relative(path.join(ROOT, 'templates'), f).replace(/\.mjs$/, '');
    const t = await import(pathToFileURL(f).href); const m = typeof t.meta === 'function' ? t.meta({}) : t.meta;
    console.log(`${name.padEnd(30)} ${(m.kind === 'pdf' ? m.size ?? 'PDF' : `${m.width}x${m.height} PNG`).padEnd(22)} ${m.about ?? ''}`);
  }
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  (async () => {
    if (flag('list')) return list();
    const files = flag('all') ? walk(path.join(ROOT, 'samples')).filter((f) => f.endsWith('.json') && JSON.parse(fs.readFileSync(f, 'utf8')).template).sort()
      : a.filter((x, i) => !x.startsWith('--') && a[i - 1] !== '--out');
    if (!files.length) { console.log(fs.readFileSync(new URL(import.meta.url), 'utf8').split('\n').filter((l) => l.startsWith('//')).join('\n')); return; }
    let faults = 0;
    for (const f of files) { try { faults += (await make(f)).faults.length; } catch (e) { faults++; console.log(`ERROR ${f}: ${e.message}`); } }
    await close();
    if (flag('check') && faults) { console.log(`${faults} fault(s)`); process.exit(1); }
  })().catch((e) => { console.error(e); process.exit(1); });
}
