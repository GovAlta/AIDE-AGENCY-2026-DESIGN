#!/usr/bin/env python3
"""Agency 2026 email: an Outlook signature and a 600 px announcement, built from brand/tokens/tokens.json.

    python3 scripts/docx/build_email.py [--palette compliant|mvai] [--img-base https://host/path/]
        -> brand/email/signature.html, signature.txt, announcement.html

Signature: image-free on purpose. Outlook blocks or strips embedded (data URI) and remote images in many setups, so the "Agency 2026"
mark is live text and the spectrum rule is a row of coloured table cells. It survives copy and paste into Outlook, Gmail and Teams.
Announcement: table layout, inline styles, 600 px, a "bulletproof" button (VML for Outlook on Windows, a padded link elsewhere). The header
is HTML too; pass --img-base to add the email-header PNG (out/digital/email-header*.png) once it is hosted at a public https address.
Placeholders are in [square brackets]. Replace them; keep the structure.
"""
import json, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
T = json.loads((ROOT / "brand/tokens/tokens.json").read_text()); E = T["event"]
a = sys.argv[1:]; pal = a[a.index("--palette") + 1] if "--palette" in a else "compliant"; img = a[a.index("--img-base") + 1] if "--img-base" in a else ""
if pal == "mvai":
    c = T["color"]; NAVY, RED, BLUE, MUTE, RULE, GROUND = c["navy"], c["maroon"], c["blue"], c["mute"], "#D0D1DB", c["field"]; SPEC = T["spectrum"]
    FONT = f"{T['font']['display']}, Arial, Helvetica, sans-serif"
else:
    c = T["compliant"]["color"]; NAVY, RED, BLUE, MUTE, RULE, GROUND = c["navy"], c["red"], c["blue"], "#4F6274", c["rule"], c["ground"]
    SPEC = [c["plum"], c["blue"], c["cyan"], c["pink"], c["orange"], c["yellow"], c["green"]]; FONT = "Arial, Helvetica, sans-serif"
OUT = ROOT / "brand/email"; OUT.mkdir(parents=True, exist_ok=True)

def trace_rule(width):
    """the trace underline as table cells (image-free): a thin blue line ending in a small ring pad (owner 2026-11-11: no rainbow)"""
    return (f'<table role="presentation" cellpadding="0" cellspacing="0" border="0" style="border-collapse:collapse;"><tr>'
            f'<td width="{width - 10}" height="2" style="width:{width - 10}px;height:2px;line-height:2px;font-size:0;background:{BLUE};" bgcolor="{BLUE}">&nbsp;</td>'
            f'<td width="10" style="width:10px;font-size:9px;line-height:9px;color:{BLUE};padding:0 0 0 2px;">&#9675;</td></tr></table>')

def spectrum(width, height=3):
    w = width // len(SPEC)
    cells = "".join(f'<td width="{w}" height="{height}" style="width:{w}px;height:{height}px;line-height:{height}px;font-size:0;background:{col};" bgcolor="{col}">&nbsp;</td>' for col in SPEC)
    return f'<table role="presentation" cellpadding="0" cellspacing="0" border="0" style="border-collapse:collapse;"><tr>{cells}</tr></table>'

sig = f"""<!-- Agency 2026 email signature (image-free). Generated by scripts/docx/build_email.py; replace the [placeholders]. -->
<table role="presentation" cellpadding="0" cellspacing="0" border="0" style="border-collapse:collapse;font-family:{FONT};color:{NAVY};">
  <tr><td style="padding:0 0 2px 0;font-size:15px;line-height:20px;font-weight:bold;color:{NAVY};">[Full name]</td></tr>
  <tr><td style="padding:0;font-size:12px;line-height:17px;color:#22384C;">[Title] · [Branch or ministry]</td></tr>
  <tr><td style="padding:0 0 8px 0;font-size:12px;line-height:17px;color:#22384C;">[Phone] · <a href="mailto:[email]" style="color:{BLUE};text-decoration:underline;">[email]</a></td></tr>
  <tr><td style="padding:0 0 3px 0;font-size:14px;line-height:16px;font-weight:bold;color:{NAVY};">Agency <span style="color:{RED};">2026</span></td></tr>
  <tr><td style="padding:0 0 4px 0;">{trace_rule(112)}</td></tr>
  <tr><td style="padding:0;font-size:11px;line-height:15px;color:{RED};font-weight:bold;">{E['datesLong']}</td></tr>
  <tr><td style="padding:0;font-size:11px;line-height:15px;color:{MUTE};">{E['hostLine']}</td></tr>
</table>
"""
(OUT / "signature.html").write_text(sig)
(OUT / "signature.txt").write_text(f"[Full name]\n[Title] · [Branch or ministry]\n[Phone] · [email]\n\nAgency 2026 · {E['datesLong']}\n{E['hostLine']}\n")

btn = lambda label, href, col=BLUE: f"""<table role="presentation" cellpadding="0" cellspacing="0" border="0" style="border-collapse:collapse;"><tr><td align="center" bgcolor="{col}" style="border-radius:4px;background:{col};">
  <!--[if mso]><v:roundrect xmlns:v="urn:schemas-microsoft-com:vml" xmlns:w="urn:schemas-microsoft-com:office:word" href="{href}" style="height:44px;v-text-anchor:middle;width:240px;" arcsize="10%" stroke="f" fillcolor="{col}"><w:anchorlock/><center style="color:#ffffff;font-family:Arial,sans-serif;font-size:15px;font-weight:bold;">{label}</center></v:roundrect><![endif]-->
  <!--[if !mso]><!--><a href="{href}" style="display:inline-block;padding:12px 26px;font-family:{FONT};font-size:15px;line-height:20px;font-weight:bold;color:#ffffff;text-decoration:none;border-radius:4px;background:{col};">{label}</a><!--<![endif]-->
</td></tr></table>"""

days = "".join(f"""<tr><td style="padding:0 0 14px 0;"><table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" style="border-collapse:collapse;"><tr>
  <td width="5" bgcolor="{col}" style="width:5px;background:{col};font-size:0;">&nbsp;</td>
  <td style="padding:10px 14px;background:{GROUND};" bgcolor="{GROUND}">
    <div style="font-family:{FONT};font-size:12px;line-height:16px;font-weight:bold;color:{RED};">{d['day']}</div>
    <div style="font-family:{FONT};font-size:17px;line-height:22px;font-weight:bold;color:{NAVY};">{d['title']}</div>
    <div style="font-family:{FONT};font-size:13px;line-height:18px;color:#22384C;">{d['sub']} · {d['place']}</div></td></tr></table></td></tr>"""
               for d, col in zip(E["days"], [T["compliant"]["color"][k] for k in ("blue", "plum", "orange")]))
hero = (f'<tr><td><img src="{img}email-header.png" width="600" alt="Agency 2026, {E["datesLong"]}" style="display:block;width:100%;max-width:600px;height:auto;border:0;"></td></tr>' if img else
        f"""<tr><td bgcolor="#FFFFFF" style="padding:28px 32px 18px 32px;background:#FFFFFF;">
  <div style="font-family:{FONT};font-size:11px;line-height:14px;letter-spacing:2px;font-weight:bold;color:{NAVY};text-transform:uppercase;">{E['hostLine']}</div>
  <div style="font-family:{FONT};font-size:44px;line-height:48px;font-weight:bold;color:{NAVY};padding:8px 0 6px 0;">Agency <span style="color:{RED};">2026</span></div>
  {trace_rule(300)}
  <div style="font-family:{FONT};font-size:16px;line-height:22px;font-weight:bold;color:{RED};padding-top:10px;">{E['datesLong']}</div></td></tr>""")
ann = f"""<!doctype html>
<html lang="en" xmlns:v="urn:schemas-microsoft-com:vml" xmlns:o="urn:schemas-microsoft-com:office:office">
<head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="x-apple-disable-message-reformatting">
<title>Agency 2026</title>
<!--[if mso]><noscript><xml><o:OfficeDocumentSettings><o:PixelsPerInch>96</o:PixelsPerInch></o:OfficeDocumentSettings></xml></noscript><![endif]-->
<!-- Agency 2026 announcement email. Generated by scripts/docx/build_email.py. Replace every [placeholder]. Event facts come from tokens.json. -->
</head>
<body style="margin:0;padding:0;background:{GROUND};">
<div style="display:none;max-height:0;overflow:hidden;">[Preview text: one line that shows in the inbox list]</div>
<table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0" bgcolor="{GROUND}" style="background:{GROUND};"><tr><td align="center" style="padding:24px 12px;">
<table role="presentation" width="600" cellpadding="0" cellspacing="0" border="0" style="width:600px;max-width:600px;border-collapse:collapse;background:#FFFFFF;border:1px solid {RULE};">
  {hero}
  <tr><td style="padding:8px 32px 6px 32px;font-family:{FONT};">
    <h1 style="margin:0 0 10px 0;font-size:24px;line-height:30px;font-weight:bold;color:{NAVY};">[Headline: one plain sentence]</h1>
    <p style="margin:0 0 16px 0;font-size:15px;line-height:22px;color:#22384C;">[One or two short sentences: who it is for and what they get.]</p></td></tr>
  <tr><td style="padding:4px 32px 4px 32px;"><table role="presentation" width="100%" cellpadding="0" cellspacing="0" border="0">{days}</table></td></tr>
  <tr><td style="padding:6px 32px 26px 32px;">{btn('[Button label]', '[https://link]')}</td></tr>
  <tr><td bgcolor="{NAVY}" style="padding:16px 32px;background:{NAVY};font-family:{FONT};font-size:12px;line-height:18px;color:#FFFFFF;">
    {E['anchor']}<br>[Contact line: name and email]<br><span style="color:#C9D6E2;">{T['classification']['default']}</span></td></tr>
</table></td></tr></table>
</body></html>
"""
(OUT / "announcement.html").write_text(ann)
print("brand/email/signature.html, signature.txt, announcement.html  (palette", pal + ")")
