// tokens.json -> styles/tokens.css (CSS custom properties + @font-face) and brand/tokens/tokens.js (window.AGENCY for browser canvases).
//   node scripts/build-tokens.mjs
// Never edit the outputs by hand: change brand/tokens/tokens.json and run this again.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const T = JSON.parse(fs.readFileSync(path.join(ROOT, 'brand/tokens/tokens.json'), 'utf8'));
const kebab = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase();
const strip = (o) => Object.fromEntries(Object.entries(o).filter(([k]) => !k.startsWith('$')));

const faces = [
  ['Inter', 400, 'Inter-Regular.otf', 'opentype'], ['Inter', 500, 'Inter-Medium.otf', 'opentype'], ['Inter', 600, 'Inter-SemiBold.otf', 'opentype'],
  ['Inter', 700, 'Inter-Bold.otf', 'opentype'], ['Inter', 800, 'Inter-ExtraBold.otf', 'opentype'],
  ['Geist Mono', 400, 'GeistMono-Regular.ttf', 'truetype'], ['Geist Mono', 500, 'GeistMono-Medium.ttf', 'truetype'],
  ['Geist Mono', 600, 'GeistMono-SemiBold.ttf', 'truetype'], ['Geist Mono', 700, 'GeistMono-Bold.ttf', 'truetype'],
];
let css = `/* GENERATED by scripts/build-tokens.mjs from brand/tokens/tokens.json (v${T.version}). Do not edit. */\n`;
for (const [fam, w, file, fmt] of faces) css += `@font-face { font-family: "${fam}"; font-weight: ${w}; font-style: normal; font-display: block; src: url("../brand/fonts/${file}") format("${fmt}"); }\n`;
css += ':root {\n';
for (const [k, v] of Object.entries(strip(T.color))) css += `  --${kebab(k)}: ${v};\n`;
for (const [k, v] of Object.entries(strip(T.textOnLight))) css += `  --text-${kebab(k)}: ${v};\n`;
for (const [k, v] of Object.entries(strip(T.textOnDark))) css += `  --text-dark-${kebab(k)}: ${v};\n`;
css += `  --spectrum: linear-gradient(90deg, ${T.spectrum.join(', ')});\n`;
css += `  --spectrum-v: linear-gradient(180deg, ${T.spectrum.join(', ')});\n`;
css += `  --font-display: "${T.font.display}", ${T.font.fallbackDisplay}, sans-serif;\n  --font-mono: "${T.font.mono}", ${T.font.fallbackMono}, monospace;\n`;
for (const [k, v] of Object.entries(strip(T.type.print))) css += `  --pt-${k}: ${v}pt;\n`;
for (const [k, v] of Object.entries(strip(T.shape))) css += `  --${kebab(k)}: ${v}px;\n`;
css += `  --ease: ${T.motion.ease};\n}\n`;
// grounds as classes: .g-board .g-paper .g-night .g-navy .g-spectrum (set --g-bg --g-ink --g-soft --g-field --g-line)
for (const [name, g] of Object.entries(strip(T.grounds))) {
  css += `.g-${name} { --g-bg: ${g.bg}; --g-ink: ${g.ink}; --g-soft: ${g.soft}; --g-field: ${g.field}; --g-line: ${g.fieldLine}; background: ${name === 'spectrum' ? 'linear-gradient(120deg, ' + T.spectrum.slice(0, 3).join(', ') + ')' : g.bg}; color: ${g.ink}; }\n`;
}
// accent helpers: .a-<name> sets --c (fill colour) and --ct (text-safe colour) for light grounds; inside dark grounds --ct flips
for (const name of [...T.spectrumNames, 'maroon', 'navy', 'rose', 'lime']) {
  const fill = T.color[name];
  css += `.a-${name} { --c: ${fill}; --ct: ${T.textOnLight[name] || fill}; }\n`;
  css += `.g-night .a-${name}, .g-navy .a-${name}, .g-spectrum .a-${name}, .dark .a-${name} { --ct: ${T.textOnDark[name] || fill}; }\n`;
}
fs.writeFileSync(path.join(ROOT, 'styles/tokens.css'), css);
fs.writeFileSync(path.join(ROOT, 'brand/tokens/tokens.js'), `/* GENERATED from tokens.json. */\nwindow.AGENCY = ${JSON.stringify(T, null, 1)};\n`);
console.log('styles/tokens.css, brand/tokens/tokens.js  (tokens v' + T.version + ')');
